public class Main {
    public static void main(String[] args) {
        System.out.println("Hello Vistula");

        int a = 5;
        int b = 10;
        int sum = a + b;
        System.out.println("Sum: " + sum);

        for (int i = 1; i <= 3; i++) {
            int square = i * i;
            System.out.println("Square of " + i + " is " + square);
        }

        System.out.println("Done");
    }
}
